import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {AUDIBLE_SEED_BOOKS} from '../src/audio/audibleSeed.js';
import {fetchAudibleCatalogMetadata} from '../src/audio/audibleMetadata.js';

const here=path.dirname(fileURLToPath(import.meta.url));
const target=path.resolve(here,'../src/audio/audibleCatalogSnapshot.js');
const coversDir=path.resolve(here,'../public/audible-covers');

export function snapshotModule(metadata,generatedAt=new Date().toISOString()){
  const out={};
  for(const [asin,item] of metadata){
    if(!asin)continue;
    const sourceCoverImageUrl=item?.coverImageUrl||null;
    const coverImageUrl=sourceCoverImageUrl?`/audible-covers/${asin}.jpg`:null;
    const runtimeMinutes=Number(item?.runtimeMinutes)>0?Math.round(Number(item.runtimeMinutes)):null;
    if(coverImageUrl||runtimeMinutes)out[asin]={coverImageUrl,sourceCoverImageUrl,runtimeMinutes};
  }
  return `// Generated by scripts/enrich-audible-catalog.mjs.\nexport const AUDIBLE_CATALOG_SNAPSHOT=${JSON.stringify(out,null,2)};\nexport const AUDIBLE_CATALOG_SNAPSHOT_GENERATED_AT=${JSON.stringify(generatedAt)};\n`;
}

async function main(){
  const asins=AUDIBLE_SEED_BOOKS.map(book=>book.asin).filter(Boolean);
  const metadata=await fetchAudibleCatalogMetadata(asins,{batchSize:50});
  await fs.mkdir(coversDir,{recursive:true});
  let cached=0;
  for(const [asin,item] of metadata){
    if(!item?.coverImageUrl)continue;
    try{
      const response=await fetch(item.coverImageUrl);
      if(!response.ok)throw new Error(`HTTP ${response.status}`);
      const bytes=Buffer.from(await response.arrayBuffer());
      if(bytes.length<1000)throw new Error('image payload too small');
      await fs.writeFile(path.join(coversDir,`${asin}.jpg`),bytes);
      cached++;
    }catch(error){console.warn(`Cover cache failed for ${asin}: ${error.message}`);item.coverImageUrl=null;}
  }
  await fs.writeFile(target,snapshotModule(metadata),'utf8');
  const covers=[...metadata.values()].filter(item=>item.coverImageUrl).length;
  const runtimes=[...metadata.values()].filter(item=>item.runtimeMinutes).length;
  console.log(`Audible catalog snapshot written: ${metadata.size} products, ${covers} covers resolved, ${cached} covers cached locally, ${runtimes} runtimes.`);
}

if(process.argv[1]===fileURLToPath(import.meta.url))main().catch(error=>{console.error(error?.stack||error);process.exitCode=1});
